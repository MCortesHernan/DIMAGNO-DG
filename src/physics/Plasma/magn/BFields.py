class MagneticField_Loop_3D(BField3D):

    '''
    Magnetic field generated by a set of circular loops 
    centered at z = -0.01, r = R_C and radius R_L.
    The displacement in z is done to avoid the peak in the poisition od the coil.
    '''

    np.ellipk = ellipk_sp
    np.ellipe = ellipe_sp
    ufl.ellipk = ellipk
    ufl.ellipe = ellipe
    
    def __init__(self, R_L=[1.], I=[1.], CN=[[0., 0., 0.]]):
        self.R_L = R_L # Radius of the coil
        self.I = I # current of wires
        self.CN = CN # center of the loop
     
    def psi(self, z=0., x=0., y=0., lib=np):
        '''
        Returns the streamcurrent at a given (set of) point(s).
        '''
        psi = z*0. # allocate and zero
        
        for i in range(len(self.R_L)):
            z_updt = z - self.CN[i][0]
            x_updt = x - self.CN[i][1]
            y_updt = y - self.CN[i][2]
            r = lib.sqrt(x_updt**2 + y_updt**2)
            
            k_2 = 4*self.R_L[i]*r*((self.R_L[i] + r)**2 + (z_updt-0.01)**2)**(-1)
            psi += mu_0*self.I[i]/(4*lib.pi) * lib.sqrt((self.R_L[i] + r)**2 + z_updt**2)*((2-k_2)*lib.ellipk(k_2) - 2*lib.ellipe(k_2))

        return psi

    def Bz(self, z=0., x=0., y=0., lib=np): 
        '''
        Returns the magnetic field in the z direction at a given (set of) point(s).
        '''
        
        Bz = z*0. # allocate and zero
        for i in range(len(self.R_L)):
            z_updt = z - self.CN[i][0]
            x_updt = x - self.CN[i][1]
            y_updt = y - self.CN[i][2]
            r = lib.sqrt(x_updt**2 + y_updt**2)
            C = self.I[i]*mu_0/lib.pi
            alpha2 = (self.R_L[i] - r)**2 + (z_updt - 0.01)**2
            beta2 = (self.R_L[i] + r)**2 + (z_updt - 0.01)**2
            k2 = 1 - alpha2/beta2

            Bz += C/(2*alpha2*beta2**0.5)*(alpha2*lib.ellipk(k2) + (self.R_L[i]**2 - r**2 - (z_updt - 0.01)**2)*lib.ellipe(k2))

        return Bz

    def Bx(self, z=0., x=0., y=0., lib=np): 
        '''
        Returns the magnetic field in the x direction at a given (set of) point(s).
        '''
        
        Br = z*0. # allocate and zero
        Bx = z*0. # allocate and zero
        for i in range(len(self.R_L)):
            z_updt = z - self.CN[i][0]
            x_updt = x - self.CN[i][1]
            y_updt = y - self.CN[i][2]
            r = lib.sqrt(x_updt**2 + y_updt**2)
            theta = lib.arctan2(x_updt,y_updt)
            C = self.I[i]*mu_0/lib.pi
            alpha2 = (self.R_L[i] - r)**2 + (z_updt - 0.01)**2
            beta2 = (self.R_L[i] + r)**2 + (z_updt - 0.01)**2
            k2 = 1 - alpha2/beta2
            Br = C*z_updt/(2*alpha2*beta2**0.5*(r+1e-12))*( - alpha2*lib.ellipk(k2) + (self.R_L[i]**2 + r**2 + (z_updt - 0.01)**2)*lib.ellipe(k2))
            Bx += Br*np.sin(theta)
        return Bx
    
    def By(self, z=0., x=0., y=0., lib=np): 
        '''
        Returns the magnetic field in the y direction at a given (set of) point(s).
        '''
        
        Br = z*0. # allocate and zero
        By = z*0. # allocate and zero
        for i in range(len(self.R_L)):
            z_updt = z - self.CN[i][0]
            x_updt = x - self.CN[i][1]
            y_updt = y - self.CN[i][2]
            r = lib.sqrt(x_updt**2 + y_updt**2)
            theta = lib.arctan2(x_updt, y_updt)
            C = self.I[i]*mu_0/lib.pi
            alpha2 = (self.R_L[i] - r)**2 + (z_updt - 0.01)**2
            beta2 = (self.R_L[i] + r)**2 + (z_updt - 0.01)**2
            k2 = 1 - alpha2/beta2
            
            Br = C*z_updt/(2*alpha2*beta2**0.5*(r+1e-12))*( - alpha2*lib.ellipk(k2) + (self.R_L[i]**2 + r**2 + (z_updt - 0.01)**2)*lib.ellipe(k2))
            By += Br*lib.cos(theta)
            
        return By

    def rescale(self, z=0., x=0., y=0., lib=np):
        '''
        Rescale the currents I so that the norm of the magnetic field at a given point is 1.
        '''
        Bnorm = self.Bnorm(z, x, y)
        self.I = [I/Bnorm for I in self.I]
