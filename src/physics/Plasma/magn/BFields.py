mu_0 = 4*np.pi*1e-7 # permeability of free space, in SI units

class BField2D:
    '''
    Abstract class for magnetic fields
    '''  
    def psi(self, z=0., x=0., lib=np):
        '''
        Streamcurrent at a given (set of) point(s).
        '''
        raise NotImplementedError('Abstract class')

    def Bz(self, z=0., x=0., lib=np):
        '''
        Magnetic field in the z direction at a given (set of) point(s).
        '''
        raise NotImplementedError('Abstract class')

    def Br(self, z=0., x=0., lib=np):
        '''
        Magnetic field in the x direction at a given (set of) point(s).
        '''
        raise NotImplementedError('Abstract class')
 
    def Bnorm(self, z=0., x=0., lib=np):
        '''
        norm of the magnetic field at a given (set of) point(s).
        '''
        return lib.sqrt(self.Br(z,x)**2 + self.Bz(z,x)**2)
        
    def rescale(self, z=0., x=0., lib=np):
        '''
        Rescale the BField2D so that the norm of the magnetic field at a given point is 1.
        '''
        raise NotImplementedError('Abstract class') 


class MagneticField_Planar(BField2D):

    '''
    Magnetic field generated by a set of infinte wires perpendicular to the plane.
    '''

    def __init__(self, Z=[0., 0.], X=[1., -1.], I=[1., -1.]):
        self.Z = Z # z-coordinates of wires
        self.X = X # x-coordinates of wires
        self.I = I # current of wires
    
    def psi(self, z=0., x=0., lib=np):
        '''
        Returns the streamcurrent at a given (set of) point(s).
        '''
        psi = z*0. # allocate and zero
        for i in range(len(self.Z)):
            psi += -mu_0*self.I[i]/(4*lib.pi) * lib.ln((z - self.Z[i])**2 + (x - self.X[i])**2)

        return psi

    def Bz(self, z=0., x=0., lib=np):
        '''
        Returns the magnetic field in the z direction at a given (set of) point(s).
        '''
        Bz = z*0. # allocate and zero
        for i in range(len(self.Z)):
            Bz += -mu_0*self.I[i]/(2*lib.pi) * (x - self.X[i]) / ((z - self.Z[i])**2 + (x - self.X[i])**2)

        return Bz

    def Br(self, z=0., x=0., lib=np):
        '''
        Returns the magnetic field in the x direction at a given (set of) point(s).
        Name is Br for consistency between planar and axisymmetric case.
        '''
        Br = z*0. # allocate and zero
        for i in range(len(self.Z)):
            Br += +mu_0*self.I[i]/(2*lib.pi) * (z - self.Z[i]) / ((z - self.Z[i])**2 + (x - self.X[i])**2)

        return Br

    def rescale(self, z=0., x=0., lib=np):
        '''
        Rescale the currents I so that the norm of the magnetic field at a given point is 1.
        '''
        Bnorm = self.Bnorm(z, x)
        self.I = [I/Bnorm for I in self.I]



class MagneticField_Loop(BField2D):

    '''
    Magnetic field generated by a set of circular loops 
    centered at z = -0.01, r = R_C and radius R_L.
    The displacement in z is done to avoid the peak in the poisition od the coil.
    '''

    np.ellipk = ellipk_sp
    np.ellipe = ellipe_sp
    ufl.ellipk = ellipk
    ufl.ellipe = ellipe
    np.ellippi = ellippi
    ufl.ellippi = ellippi

    def __init__(self, R_L=[1.], I=[1.]):
        self.R_L = R_L # Radius of the coil
        self.I = I # current of wires
    
    def psi(self, z=0., x=0., lib=np):
        '''
        Returns the streamcurrent at a given (set of) point(s).
        '''
        psi = z*0. # allocate and zero
        for i in range(len(self.R_L)):

            k_2 = 4*self.R_L[i]*x*((self.R_L[i] + x)**2 + (z-0.01)**2)**(-1)
            psi += mu_0*self.I[i]/(4*lib.pi) * lib.sqrt((self.R_L[i] + x)**2 + z**2)*((2-k_2)*lib.ellipk(k_2) - 2*lib.ellipe(k_2))

        return psi
    
    def Chi(self, z=0., x=0., lib=np):
        '''
        Returns the magnetic potential Chi at a given (set of) point(s).
        '''
        Chi = z*0. # allocate and zero
        for i in range(len(self.R_L)):
            eps = 1e-3 # to avoid singularities
            k_2 = 4*self.R_L[i]*x*((self.R_L[i] + x)**2 + (z)**2 + eps**2)**(-1)
            n = 4*self.R_L[i]*x/((self.R_L[i] - x)**2 + (z)**2 + eps**2)
            Omega = (2*self.R_L[i]/((self.R_L[i] + x)**2 + (z)**2 + eps**2)**0.5)*lib.ellipk(k_2) - 2*lib.ellippi(n, k_2)
            Chi += mu_0*self.I[i]/(4*lib.pi) * Omega

        return Chi

    def Bz(self, z=0., r=0., lib=np): 
        '''
        Returns the magnetic field in the z direction at a given (set of) point(s).
        '''
        Bz = z*0. # allocate and zero
        for i in range(len(self.R_L)):
            C = self.I[i]*mu_0/lib.pi
            alpha2 = (self.R_L[i] - r)**2 + (z - 0.01)**2
            beta2 = (self.R_L[i] + r)**2 + (z - 0.01)**2
            k2 = 1 - alpha2/beta2

            Bz += C/(2*alpha2*beta2**0.5)*(alpha2*lib.ellipk(k2) + (self.R_L[i]**2 - r**2 - (z - 0.01)**2)*lib.ellipe(k2))

        return Bz

    def Br(self, z=0., r=0., lib=np): 
        '''
        Returns the magnetic field in the x direction at a given (set of) point(s).
        '''

        Br = z*0. # allocate and zero
        for i in range(len(self.R_L)):
            C = self.I[i]*mu_0/lib.pi
            alpha2 = (self.R_L[i] - r)**2 + (z - 0.01)**2
            beta2 = (self.R_L[i] + r)**2 + (z - 0.01)**2
            k2 = 1 - alpha2/beta2
            
            Br += C*z/(2*alpha2*beta2**0.5*(r+1e-12))*( - alpha2*lib.ellipk(k2) + (self.R_L[i]**2 + r**2 + (z - 0.01)**2)*lib.ellipe(k2))
        
        return Br

    def rescale(self, z=0., r=0., lib=np):
        '''
        Rescale the currents I so that the norm of the magnetic field at a given point is 1.
        '''
        Bnorm = self.Bnorm(z, r)
        self.I = [I/Bnorm for I in self.I]


class Streamline_Tracing:
    '''
    Class for the tracing of magnetic field lines in 2D.
    '''
    def __init__(self, BField2D, z_grid, x_grid, N_points):
        self.BField2D = BField2D
        self.z_grid = z_grid
        self.x_grid = x_grid
        self.N_points = N_points

    def resample_streamline(self, streamline_path):
        """
        Resample a streamline path to N_points with uniform arc-length spacing.
        Returns (resampled_path, arc_length).
        """
        x, z = streamline_path[:,0], streamline_path[:,1]

        # parameter t along curve (0 → 1)
        t = np.linspace(0, 1, len(x))

        # spline fit (no smoothing, exact fit)
        tck, _ = splprep([x, z], s=0)

        # uniform parameterization
        t_new = np.linspace(0, 1, self.N_points)
        x_new, z_new = splev(t_new, tck)

        # arc length calculation
        dx = np.diff(x_new)
        dz = np.diff(z_new)
        ds = np.sqrt(dx**2 + dz**2)
        s = np.zeros_like(x_new)
        s[1:] = np.cumsum(ds)

        resampled_path = np.vstack([x_new, z_new]).T
        return resampled_path, s
    
    def streamline_mapping(self, psi_level):
        """
        Extract one streamline for a given psi_level, resample it, 
        and return (resampled_path, arc_length).
        """
        cs = plt.contour(self.z_grid, self.x_grid, self.BField2D.psi(self.z_grid, self.x_grid), levels=[psi_level])
        paths = cs.collections[0].get_paths()
        streamline_path = paths[0].vertices  # take first path
        #plt.show()
        plt.close()

        return self.resample_streamline(streamline_path)

